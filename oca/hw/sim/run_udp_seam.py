"""Run the UDP seam cocotb tests under the project-local Verilator.

The seam is exercised against the real oca_core, not a stub, because the
property under test is that the header queue stays in step with the core's
responses -- and the one input that breaks that step is a request the core
answers with nothing at all (oca_proto.sv:779). A stub written from the same
reading of oca_proto as the seam would agree with the seam's mistakes.

Two modules therefore have to elaborate together, and cocotb takes one
toplevel, so the harness below is written into the build directory rather
than kept as a fourth source file. It is structure only -- two instances and
the wires between them -- and generating it keeps the parameters the tests
assume and the parameters the design is elaborated with from drifting apart.
"""

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
VERILATOR_BIN = ROOT / "tools" / "verilator" / "bin"
RTL = ROOT / "oca" / "hw" / "rtl"

os.environ["PATH"] = str(VERILATOR_BIN) + os.pathsep + os.environ["PATH"]

try:
    from cocotb.runner import get_runner  # cocotb 1.x  # noqa: E402
except ModuleNotFoundError:
    from cocotb_tools.runner import get_runner  # cocotb 2.x  # noqa: E402
from cocotb_tools.check_results import get_results  # noqa: E402

SIM_DIR = Path(__file__).resolve().parent

# Imported by test_udp_seam.py rather than repeated there, so that a change to
# the elaboration cannot leave the expectations behind.
LOCAL_IP = 0xC0A80164
LOCAL_PORT = 5000
HDR_Q_DEPTH = 8
REPLY_TTL = 64

# The suite runs twice. At the shipping depth the queue must never fill, and
# the watermark says how much of it the worst traced case actually used. At
# depth 2 it must fill, which is the only way the guard -- hq_full stopping
# admission, and the drop landing on cnt_drop_full -- is executed at all
# rather than carried as unreachable code.
DEPTHS = (HDR_Q_DEPTH, 2)


