SOURCES = [
    RTL / "chacha20.sv",
    RTL / "poly1305.sv",
    RTL / "chacha20_poly1305.sv",
    RTL / "oca_keystore.sv",
    RTL / "oca_pktbuf.sv",
    RTL / "oca_proto.sv",
    RTL / "oca_core.sv",
    RTL / "oca_udp_seam.sv",
]


def failed_tests() -> int:
    """Red tests in the run that just finished.

    runner.test() only inspects results.xml under pytest, and Verilator exits
    0 on $finish even with failing tests: without this check the process exits
    0 however the suite went, and anything driving these runners by exit code
    would call a red suite green.
    """
    num_tests, num_failed = get_results(SIM_DIR / "results.xml")
    if num_tests == 0:
        raise RuntimeError("results.xml records no tests")
    return num_failed


def lint() -> int:
    """Refuse -Wall findings in the seam before anything is simulated."""
    import subprocess
    proc = subprocess.run(
        [str(VERILATOR_BIN / "verilator"), "--lint-only", "-Wall",
         str(RTL / "oca_udp_seam.sv"), "--top-module", "oca_udp_seam"],
        capture_output=True, text=True)
    if proc.returncode != 0:
        print(proc.stdout + proc.stderr, flush=True)
        print("lint: FAILED", flush=True)
        return 1
    print("lint: ok", flush=True)
    return 0


def write_harness(depth: int) -> Path:
    out = build_dir(depth)
    out.mkdir(parents=True, exist_ok=True)
    path = out / "tb_udp_seam.sv"
    path.write_text(HARNESS % {"local_ip": LOCAL_IP, "local_port": LOCAL_PORT,
                               "reply_ttl": REPLY_TTL, "depth": depth,
                               "wm_hi": (depth - 1).bit_length()})
    return path


def run_at(depth: int) -> int:
    harness = write_harness(depth)
    runner = get_runner("verilator")
    runner.build(
        sources=SOURCES + [harness],
        hdl_toplevel="tb_udp_seam",
        build_dir=build_dir(depth),
        always=True,
    )
    (SIM_DIR / "results.xml").unlink(missing_ok=True)  # never grade a stale file
    os.environ["OCA_SEAM_DEPTH"] = str(depth)
    runner.test(
        hdl_toplevel="tb_udp_seam",
        test_module="test_udp_seam",
        test_dir=SIM_DIR,
        build_dir=build_dir(depth),
        extra_env={"OCA_SEAM_DEPTH": str(depth)},
    )
    failed = failed_tests()
    print(f"HDR_Q_DEPTH={depth}: {failed} failed", flush=True)
    return failed


def main() -> int:
    rc = lint()
    if rc != 0:
        return rc
    return 1 if sum(run_at(d) for d in DEPTHS) else 0


if __name__ == "__main__":
    sys.exit(main())
